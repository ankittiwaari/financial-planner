package com.algopraxis.dhanniti.ui.dues

import com.algopraxis.dhanniti.domain.Due
import com.algopraxis.dhanniti.domain.DueSource
import com.algopraxis.dhanniti.domain.DueStatus
import com.algopraxis.dhanniti.domain.Money
import com.algopraxis.dhanniti.ui.cards.CardsViewModel
import kotlinx.datetime.LocalDate
import kotlin.test.Test
import kotlin.test.assertEquals

class DueGroupingTest {
    // Thursday 29 Oct 2026.
    private val today = LocalDate(2026, 10, 29)

    private fun due(id: Long, date: LocalDate, status: DueStatus = DueStatus.UPCOMING, paidOn: LocalDate? = null) = Due(
        id = id, sourceType = DueSource.LOAN, sourceId = 1, period = "2026-11", title = "Due $id", amount = Money(100),
        dueDate = date, status = status, paidOn = paidOn,
    )

    @Test
    fun groupsOpenDuesByWeekWithOverdueFirst() {
        val dues = listOf(
            due(1, LocalDate(2026, 11, 17)),
            due(2, LocalDate(2026, 10, 30)), // Friday this week
            due(3, LocalDate(2026, 10, 20), DueStatus.OVERDUE),
            due(4, LocalDate(2026, 11, 2)), // Monday next week
            due(5, LocalDate(2026, 11, 5)),
            due(6, LocalDate(2026, 10, 1), DueStatus.PAID, paidOn = LocalDate(2026, 10, 1)),
        )

        val groups = DuesViewModel.groupDues(dues, DueFilter.OPEN, today)

        assertEquals(listOf("Overdue", "This week", "Next week", "Week of 16 Nov"), groups.map { it.label })
        assertEquals(listOf(listOf(3L), listOf(2L), listOf(4L, 5L), listOf(1L)), groups.map { g -> g.dues.map { it.id } })
    }

    @Test
    fun groupsPaidDuesByMonthNewestFirst() {
        val dues = listOf(
            due(1, LocalDate(2026, 10, 1), DueStatus.PAID, paidOn = LocalDate(2026, 9, 30)),
            due(2, LocalDate(2026, 11, 1), DueStatus.PAID, paidOn = LocalDate(2026, 10, 29)),
            due(3, LocalDate(2026, 11, 5)),
        )

        val groups = DuesViewModel.groupDues(dues, DueFilter.PAID, today)

        assertEquals(listOf("Oct 2026", "Sep 2026"), groups.map { it.label })
        assertEquals(listOf(2L, 1L), groups.flatMap { g -> g.dues.map { it.id } })
    }

    @Test
    fun offersTheLatestStatementMonthsForABill() {
        // Statement on the 28th: October's has been generated by the 29th.
        assertEquals(listOf("2026-10", "2026-09", "2026-08"), CardsViewModel.statementPeriodChoices(today, 28))
        assertEquals(listOf("2026-09", "2026-08", "2026-07"), CardsViewModel.statementPeriodChoices(today, 30))
        // Day 31 in a 30-day month means the 30th.
        assertEquals("2026-11", CardsViewModel.statementPeriodChoices(LocalDate(2026, 11, 30), 31).first())
    }
}
